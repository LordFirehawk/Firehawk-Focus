import SwiftUI

/// Who made each recording, under which licence, and where it came from.
/// Reached from Settings and from the foot of the Sounds mixer.
struct SoundCreditsView: View {
    let catalog: [SoundDescriptor]
    let onBack: () -> Void

    private var recordedGroups: [(category: SoundCategory, credits: [SoundCredit])] {
        let recorded = catalog.filter { !$0.isGenerated }.map(SoundCredit.init)
        let byCategory = Dictionary(grouping: recorded, by: \.category)
        return SoundCategory.allCases.compactMap { category in
            guard let items = byCategory[category], !items.isEmpty else { return nil }
            return (category, items)
        }
    }

    private var generated: [SoundDescriptor] { catalog.filter(\.isGenerated) }

    var body: some View {
        VStack(spacing: 0) {
            SoundsBackBar(title: "Sound credits", onBack: onBack)
            Divider()

            ScrollView {
                VStack(alignment: .leading, spacing: 0) {
                    Text("These recordings were shared by the people below. Each is used under the licence shown.")
                        .font(.system(size: 11.5))
                        .foregroundStyle(.secondary)
                        .fixedSize(horizontal: false, vertical: true)
                        .padding(.bottom, 6)

                    ForEach(recordedGroups, id: \.category) { group in
                        SoundsSectionLabel(title: group.category.title)
                            .padding(.top, 14)
                            .padding(.bottom, 2)
                        ForEach(Array(group.credits.enumerated()), id: \.element.id) { index, credit in
                            if index > 0 {
                                Divider().padding(.leading, SoundsStyle.iconColumn + 10)
                            }
                            SoundCreditRow(credit: credit)
                        }
                    }

                    if !generated.isEmpty {
                        SoundsSectionLabel(title: "Generated")
                            .padding(.top, 14)
                            .padding(.bottom, 2)
                        generatedRow
                    }
                }
                .padding(.horizontal, 14)
                .padding(.top, 10)
                .padding(.bottom, 16)
            }
        }
    }

    private var generatedRow: some View {
        HStack(alignment: .top, spacing: 10) {
            SoundCreditIcon(symbolName: "waveform")
            VStack(alignment: .leading, spacing: 2) {
                Text(ListFormatter.localizedString(byJoining: generated.map(\.name)))
                    .font(.system(size: 12.5, weight: .semibold))
                    .fixedSize(horizontal: false, vertical: true)
                Text("Generated by Firehawk Focus as you listen. No recording is used.")
                    .font(.system(size: 11))
                    .foregroundStyle(.secondary)
                    .fixedSize(horizontal: false, vertical: true)
            }
        }
        .padding(.vertical, 8)
        .accessibilityElement(children: .combine)
    }
}

/// One recording: name and licence on the first line, then each source, prior editors and the edit note.
/// Sounds built from sources under different licences show a tag beside each source instead.
private struct SoundCreditRow: View {
    let credit: SoundCredit

    var body: some View {
        HStack(alignment: .top, spacing: 10) {
            SoundCreditIcon(symbolName: credit.symbolName)

            VStack(alignment: .leading, spacing: 2) {
                HStack(alignment: .firstTextBaseline, spacing: 8) {
                    Text(credit.name)
                        .font(.system(size: 12.5, weight: .semibold))
                        .lineLimit(1)
                    Spacer(minLength: 4)
                    if !credit.showsLicencePerSource {
                        SoundLicenceTag(licence: credit.sharedLicence)
                    }
                }

                VStack(alignment: .leading, spacing: credit.sources.count > 1 ? 5 : 2) {
                    ForEach(credit.sources, id: \.self) { source in
                        sourceView(source)
                    }
                }

                if let contributors = credit.contributors {
                    Text(contributors)
                        .font(.system(size: 11))
                        .foregroundStyle(.secondary)
                        .fixedSize(horizontal: false, vertical: true)
                        .textSelection(.enabled)
                }

                Text(SoundCredit.editNote)
                    .font(.system(size: 10.5))
                    .foregroundStyle(.tertiary)
                    .fixedSize(horizontal: false, vertical: true)
                    .padding(.top, 1)
            }
        }
        .padding(.vertical, 8)
    }

    private func sourceView(_ source: SoundCredit.Source) -> some View {
        VStack(alignment: .leading, spacing: 1) {
            HStack(alignment: .firstTextBaseline, spacing: 8) {
                Text(source.byline)
                    .font(.system(size: 11.5))
                    .fixedSize(horizontal: false, vertical: true)
                    .textSelection(.enabled)
                if credit.showsLicencePerSource {
                    Spacer(minLength: 4)
                    SoundLicenceTag(licence: source.licence)
                }
            }
            if let url = source.url {
                SoundCreditLink(title: SoundCredit.label(for: url), url: url, help: "Open the source page for \(credit.name)")
            }
        }
    }
}

private struct SoundCreditIcon: View {
    let symbolName: String

    var body: some View {
        Image(systemName: SoundsStyle.symbol(symbolName))
            .font(.system(size: 12, weight: .semibold))
            .foregroundStyle(.secondary)
            .frame(width: SoundsStyle.iconColumn, height: SoundsStyle.iconColumn)
            .background(SoundsStyle.surface)
            .clipShape(Circle())
            .accessibilityHidden(true)
    }
}

/// Licence name; links to the deed when the licence has one.
private struct SoundLicenceTag: View {
    let licence: SoundLicense?

    var body: some View {
        if let licence, let deed = licence.deedURL {
            Link(destination: deed) {
                label(licence.tagTitle, emphasised: true)
            }
            .buttonStyle(.plain)
            .help("Read the \(licence.tagTitle) licence")
            .accessibilityLabel("Licence \(licence.tagTitle)")
            .accessibilityHint("Opens the licence in your browser")
        } else {
            label(licence?.tagTitle ?? "Licence on source page", emphasised: false)
                .accessibilityLabel("Licence \(licence?.tagTitle ?? "on the source page")")
        }
    }

    private func label(_ text: String, emphasised: Bool) -> some View {
        Text(text)
            .font(.system(size: 10.5, weight: .semibold))
            .foregroundStyle(emphasised ? SoundsStyle.emberText : Color.secondary)
            .padding(.horizontal, 7)
            .padding(.vertical, 2)
            .background(emphasised ? SoundsStyle.ember.opacity(0.14) : SoundsStyle.surface)
            .clipShape(Capsule())
            .fixedSize()
    }
}

/// Text link that opens in the default browser.
struct SoundCreditLink: View {
    let title: String
    let url: URL
    var help: String? = nil
    @State private var isHovering = false

    var body: some View {
        Link(destination: url) {
            HStack(spacing: 3) {
                Text(title)
                    .underline(isHovering)
                Image(systemName: "arrow.up.forward")
                    .font(.system(size: 8, weight: .bold))
                    .accessibilityHidden(true)
            }
            .font(.system(size: 11, weight: .medium))
            .foregroundStyle(SoundsStyle.emberText)
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .onHover { isHovering = $0 }
        .help(help ?? url.absoluteString)
        .accessibilityHint("Opens in your browser")
    }
}

/// Top bar for a pushed screen inside the tray: back on the left, title centred.
struct SoundsBackBar: View {
    let title: String
    let onBack: () -> Void

    var body: some View {
        ZStack {
            Text(title)
                .font(.system(size: 13, weight: .semibold))
                .accessibilityAddTraits(.isHeader)
            HStack {
                Button(action: onBack) {
                    Label("Back", systemImage: "chevron.left")
                        .font(.system(size: 12, weight: .medium))
                        .labelStyle(.titleAndIcon)
                        .padding(.horizontal, 6)
                        .frame(minHeight: 24)
                        .contentShape(Rectangle())
                }
                .buttonStyle(.plain)
                .foregroundStyle(.secondary)
                .keyboardShortcut("[", modifiers: .command)
                .help("Back (⌘[)")
                Spacer()
            }
        }
        .padding(.horizontal, 8)
        .frame(height: 40)
    }
}
